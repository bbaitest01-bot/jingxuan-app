-- 先刪掉這些商品舊的項目，再寫入新的
DELETE FROM public.insurance_product_benefit_items i
USING public.insurance_products p
WHERE i.product_id = p.id
  AND (p.company_code, p.product_name) IN (SELECT DISTINCT company_code, product_name FROM benefit_items_import);

INSERT INTO public.insurance_product_benefit_items (product_id, item_order, item_key, item_name, formula, source_excerpt)
SELECT p.id, v.item_order, v.item_key, v.item_name, v.formula, v.source_excerpt
FROM benefit_items_import v
JOIN public.insurance_products p ON p.company_code = v.company_code AND p.product_name = v.product_name;

DROP TABLE benefit_items_import;

